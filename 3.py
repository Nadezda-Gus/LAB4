while True:
    try:
        k = float(input("\nВведите размер кредита (k, руб.): "))
        p = float(input("Введите процентную ставку (p, %): "))
        r = float(input("Введите ежегодную прибыль (r, руб.): "))
        if k <= 0 or p <= 0 or r <= 0:
            print("Ошибка: все значения должны быть положительными.")
        elif r <= k * (p / 100):
            print("\nВывод: Кредит НЕ может быть погашен.")
            print(f"Прибыль ({r} руб.) не покрывает даже начисляемые проценты ({k * (p / 100):.2f} руб. в год).")
        else:
            debt = k
            years = 0
            while debt > 0:
                debt = debt * (1 + p / 100)
                debt = debt - r
                years += 1
                if years > 100:
                    break
            if debt <= 0:
                print(f"\nВывод: Предприниматель сможет погасить кредит за {years} лет.")
                print(f"Остаток после погашения: {abs(debt):.2f} руб.")
            else:
                print("\nВывод: За 100 лет кредит погасить не удалось (слишком медленное погашение).")
    except ValueError:
        print("Ошибка: введите корректные числовые значения.")